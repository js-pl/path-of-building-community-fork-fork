//! Translates the engine API's Lua bridge (`lua/session.lua`) with luagen
//! (with the `translation` feature), and evaluates upstream's `Modules/CalcSections.lua` into JSON for the
//! typed Calcs tab.

use lua::{Key, Value};
use serde_json::{Map, Value as J};
use std::path::{Path, PathBuf};

fn main() {
    let dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    if std::env::var_os("CARGO_FEATURE_TRANSLATION").is_some() {
        let src_path = dir.join("lua/session.lua");
        let src = std::fs::read(&src_path).unwrap();
        let header =
            "// @generated by luagen from crates/session/lua/session.lua; do not edit.\n\n";
        let code = importer::luagen::translate_module(&src, header)
            .unwrap_or_else(|e| panic!("luagen: lua/session.lua: {}", e.0));
        std::fs::write(out.join("session_lua.rs"), code).unwrap();
        println!("cargo:rerun-if-changed={}", src_path.display());
    }

    let up = dir.join("../../upstream/PathOfBuilding/src");
    let sections = calc_sections(&up);
    std::fs::write(out.join("calc_sections.json"), sections.to_string()).unwrap();
    println!(
        "cargo:rerun-if-changed={}",
        up.join("Modules/CalcSections.lua").display()
    );
    let stats = display_stat_compares(&up);
    std::fs::write(out.join("display_stat_compares.json"), stats.to_string()).unwrap();
    println!(
        "cargo:rerun-if-changed={}",
        up.join("Modules/BuildDisplayStats.lua").display()
    );
    let misc = up.join("Data/Misc.lua");
    std::fs::write(
        out.join("gold_respec_prices.json"),
        gold_respec_prices(&misc),
    )
    .unwrap();
    println!("cargo:rerun-if-changed={}", misc.display());
    let tab = up.join("Classes/CalcsTab.lua");
    std::fs::write(out.join("calcs_mode_tooltip.txt"), mode_tooltip(&tab)).unwrap();
    println!("cargo:rerun-if-changed={}", tab.display());
}

/// The tooltip of the Calcs tab's calculation mode: the long string after
/// its drop-down's function
fn mode_tooltip(tab: &Path) -> String {
    let s = std::fs::read_to_string(tab).unwrap().replace("\r\n", "\n");
    let start = s
        .find("self.input.misc_buffMode = value.buffMode")
        .and_then(|i| s[i..].find("end, [[\n").map(|j| i + j + 8))
        .expect("CalcsTab.lua: the calculation mode's tooltip");
    let end = start
        + s[start..]
            .find("]]")
            .expect("CalcsTab.lua: end of the tooltip");
    s[start..end].to_string()
}

/// `LoadModule("Modules/CalcSections")` with the globals of
/// `Data/Global.lua`
fn calc_sections(up: &Path) -> J {
    let mut im = importer::Importer::new(up);
    im.load("Data/Global", vec![])
        .unwrap_or_else(|e| panic!("Data/Global.lua: {e}"));
    let v = im
        .load1("Modules/CalcSections", vec![])
        .unwrap_or_else(|e| panic!("Modules/CalcSections.lua: {e}"));
    json(&v)
}

/// A table as an object with its sequence under `#`
fn json(v: &Value) -> J {
    match v {
        Value::Nil => J::Null,
        Value::Bool(b) => J::Bool(*b),
        Value::Number(n) => serde_json::Number::from_f64(*n).map_or(J::Null, J::Number),
        Value::Str(s) => J::String(s.to_str_lossy().into_owned()),
        Value::Table(t) => {
            let mut m = Map::new();
            let list: Vec<J> = t.array().iter().map(json).collect();
            for (k, x) in t.entries() {
                match k {
                    Key::Str(s) => {
                        m.insert(s.to_str_lossy().into_owned(), json(&x));
                    }
                    Key::Int(i) if i >= 1 && (i as usize) <= list.len() => {}
                    k => panic!("CalcSections.lua: unexpected key {k:?}"),
                }
            }
            if !list.is_empty() {
                m.insert("#".into(), J::Array(list));
            }
            J::Object(m)
        }
        _ => panic!("CalcSections.lua: unexpected function"),
    }
}

/// What the stat comparisons read of `Modules/BuildDisplayStats.lua`'s
/// `displayStats` and `minionDisplayStats`: each row's label,
/// `lowerIsBetter` and `compPercent`
fn display_stat_compares(up: &Path) -> J {
    let mut im = importer::Importer::new(up);
    im.load("Data/Global", vec![])
        .unwrap_or_else(|e| panic!("Data/Global.lua: {e}"));
    let v = im
        .load1("Modules/BuildDisplayStats", vec![])
        .unwrap_or_else(|e| panic!("Modules/BuildDisplayStats.lua: {e}"));
    let t = v.as_table().expect("BuildDisplayStats.lua: a table");
    let list = |name: &str| -> J {
        let l = t.get_str(name);
        let l = l.as_table().expect("BuildDisplayStats.lua: a list");
        let rows = l.array();
        let rows = rows.iter().map(|row| {
            let row = row.as_table().expect("BuildDisplayStats.lua: a row");
            let label = row.get_str("label");
            let flag = |k: &str| J::Bool(row.get_str(k).truthy());
            serde_json::json!([
                label.as_str().map(|s| s.to_str_lossy().into_owned()),
                flag("lowerIsBetter"),
                flag("compPercent"),
            ])
        });
        J::Array(rows.collect())
    };
    serde_json::json!({
        "player": list("displayStats"),
        "minion": list("minionDisplayStats"),
    })
}

/// `data.goldRespecPrices` of `Data/Misc.lua`, by character level, as a
/// JSON list
fn gold_respec_prices(misc: &Path) -> String {
    let s = std::fs::read_to_string(misc).unwrap();
    let start = s
        .find("data.goldRespecPrices = {")
        .map(|i| i + "data.goldRespecPrices = {".len())
        .expect("Misc.lua: goldRespecPrices");
    let end = start
        + s[start..]
            .find('}')
            .expect("Misc.lua: end of goldRespecPrices");
    let prices: Vec<f64> = s[start..end]
        .split(',')
        .map(str::trim)
        .filter(|v| !v.is_empty())
        .map(|v| v.parse().expect("Misc.lua: a gold price"))
        .collect();
    serde_json::to_string(&prices).unwrap()
}
